// v12 (douyin): turn the web game's body markup + CSS (index.html, album-ui / diary-ui inline CSS, xhs mobile.css, douyin overrides)
// into what the Taro overlay renders: tags become classes (.t-div), [attr] selectors become classes (.a-disabled), hidden rules are
// dropped (hidden nodes are not rendered), :hover/:active are dropped, px become PX (Taro's pxtransform leaves them alone, so the
// stylesheet and the game's inline px styles agree), url(...) assets are inlined as data URLs.
import fs from 'node:fs';
import path from 'node:path';

const HERE = path.dirname(new URL(import.meta.url).pathname);

export function bodyMarkup(html) {
  let b = html.slice(html.indexOf('<body>') + 6, html.lastIndexOf('</body>'));
  b = b.replace(/<script[\s\S]*?<\/script>/g, '');
  b = b.replace(/<canvas id="minimap"[^>]*><\/canvas>/, ''); // no minimap on the phone
  return b.replace(/\n\s*/g, '\n').trim();
}

function stripComments(css) { return css.replace(/\/\*[\s\S]*?\*\//g, ''); }
function readBlock(css, i) { // css[i] === '{' → index after the matching '}'
  let d = 0;
  for (; i < css.length; i++) { if (css[i] === '{') d++; else if (css[i] === '}' && --d === 0) return i + 1; }
  return css.length;
}
const ATTRS = new Set();
const clean = v => String(v).replace(/[^a-zA-Z0-9_-]/g, '_');
function txSelector(sel) {
  sel = sel.trim();
  if (!sel) return null;
  if (/:(hover|focus|focus-visible|focus-within|active|visited|link|target)\b/.test(sel)) return null;
  if (/::?(-webkit-|-moz-|selection|placeholder|backdrop|marker)/.test(sel)) return null;
  sel = sel.replace(/:not\(\[hidden\]\)/g, '');
  if (/\[hidden\]/.test(sel)) return null;
  const keep = [];
  sel = sel.replace(/:(nth-[a-z-]+|lang|dir)\([^)]*\)/g, m => { keep.push(m); return `\u0001${keep.length - 1}\u0001`; });
  sel = sel.replace(/\[([a-zA-Z-]+)(?:\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\]\s]*)))?\]/g, (m, k, a, b, c) => {
    k = k.toLowerCase(); ATTRS.add(k); const v = a ?? b ?? c;
    return '.a-' + k + (v != null && v !== '' ? '-' + clean(v) : '');
  });
  sel = sel.replace(/(^|[\s>+~(,])([a-z][a-z0-9]*)(?=[.#:\[\s>+~),\u0001]|$)/g, (m, pre, tag) => pre + '.t-' + tag);
  sel = sel.replace(/(^|[\s>+~(,])\*/g, '$1.pf-n');
  sel = sel.replace(/\u0001(\d+)\u0001/g, (m, i) => keep[+i]);
  return sel;
}
function txDecls(body, urls) {
  body = body.replace(/url\(\s*['"]?([^'")]+)['"]?\s*\)/g, (m, u) => {
    if (u.startsWith('data:')) return m;
    const k = path.basename(u);
    if (urls[k] === null) return 'none';
    if (!urls[k]) throw new Error('css asset not inlined: ' + u);
    return `url(${urls[k]})`;
  });
  return body.replace(/(-?\d*\.?\d+)px\b/g, '$1PX');
}
function txRules(css, urls) {
  let out = '', i = 0;
  while (i < css.length) {
    const open = css.indexOf('{', i);
    if (open < 0) break;
    const head = css.slice(i, open).trim();
    const end = readBlock(css, open);
    const inner = css.slice(open + 1, end - 1);
    i = end;
    if (/^@(-webkit-)?keyframes/.test(head)) { out += `${head}{${txDecls(inner, urls)}}\n`; continue; }
    if (/^@(media|supports)/.test(head)) { const r = txRules(inner, urls); if (r.trim()) out += `${head}{\n${r}}\n`; continue; }
    if (head.startsWith('@')) continue; // @font-face etc.
    const sels = head.split(/,(?![^(]*\))/).map(txSelector).filter(Boolean);
    if (!sels.length) continue;
    out += `${sels.join(',')}{${txDecls(inner.trim(), urls)}}\n`;
  }
  return out;
}
export function buildUi({ html, albumUi, diaryUi, hudIconsPng, outDir }) {
  const dataUrl = (buf, type) => `data:${type};base64,${buf.toString('base64')}`;
  const urls = {
    'hud_icons.png': dataUrl(hudIconsPng, 'image/png'),
    'atlas_hud_128_q90.webp': dataUrl(fs.readFileSync(path.join(HERE, 'atlas_hud_dy.png')), 'image/png'),
    'atlas_128_q90.webp': null, 'atlas_extra_128_q90.webp': null, // music / sfx / share / tip icons: not on Douyin
  };
  const gameCss = html.slice(html.indexOf('<style>') + 7, html.indexOf('</style>'));
  const inline = src => { const m = /css\.textContent = `([\s\S]*?)`;/.exec(src); if (!m || m[1].includes('${')) throw new Error('inline css not found'); return m[1]; };
  const parts = [
    ['douyin base', fs.readFileSync(path.join(HERE, 'dy-base.css'), 'utf8')], ['index.html', gameCss], ['album-ui.js', inline(albumUi)], ['diary-ui.js', inline(diaryUi)],
    ['xhs mobile.css', fs.readFileSync(path.join(HERE, 'xhs-mobile.css'), 'utf8')], ['douyin', fs.readFileSync(path.join(HERE, 'dy-ui.css'), 'utf8')],
  ];
  let css = '/* eslint-disable tailwind/no-arbitrary-font-size -- generated from the web game\'s own stylesheet; its px sizes must match the game\'s inline px */\n/* Generated by scripts/build-game.mjs (v12 douyin UI) from the web game CSS + xhs mobile.css + dy-ui.css. Do not edit by hand. */\n';
  for (const [name, src] of parts) css += `/* ---- ${name} ---- */\n` + txRules(stripComments(src), urls);
  const markup = bodyMarkup(html);
  const attrs = [...ATTRS].filter(a => a !== 'hidden').sort();
  fs.writeFileSync(path.join(outDir, 'farm-ui.css'), css);
  fs.writeFileSync(path.join(outDir, 'farm-ui-html.ts'), `// Generated by scripts/build-game.mjs from the web game's index.html body. Do not edit by hand.\nexport const FARM_UI_HTML = ${JSON.stringify(markup)}\n/** attributes that CSS selects on: the overlay adds .a-<name> / .a-<name>-<value> classes for them */\nexport const FARM_UI_ATTRS: string[] = ${JSON.stringify(attrs)}\n`);
  return { cssBytes: css.length, attrs };
}
